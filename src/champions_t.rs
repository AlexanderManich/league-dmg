fn first_in_vec<'de, D, T>(deserializer: D) -> Result<T, D::Error>
where
    D: Deserializer<'de>,
    T: Deserialize<'de>,
{
    let v: Vec<T> = Vec::deserialize(deserializer)?;
    v.into_iter()
        .next()
        .ok_or_else(|| SerdeError::custom("Expected at least one ability"))
}

