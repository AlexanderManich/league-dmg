pub fn read_item_data(item: ItemKind) -> Result<Item, Box<dyn Error>> {
    let item_id = item.id();
    let path = Path::new("items").join(format!("{item_id}.json"));
    let data = fs::read_to_string(path)?;
    let item = serde_json::from_str(&data)?;

    Ok(item)
}

